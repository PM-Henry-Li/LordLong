import { mkdir, mkdtemp, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { PinyinData } from '../data/pinyin-data.js';
import { WordsData } from '../data/words-data.js';
import { LetterPinyinSounds, PinyinSpeechMap } from '../data/voice-map.js';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const assetDirectory = resolve(projectRoot, 'audio/voice/zh');
const manifestFile = resolve(projectRoot, 'data/voice-manifest.js');

function hashText(text) {
    let hash = 2166136261;
    const value = String(text);

    for (let i = 0; i < value.length; i += 1) {
        hash ^= value.charCodeAt(i);
        hash = Math.imul(hash, 16777619);
    }

    return (hash >>> 0).toString(16);
}

function collectVoiceTexts() {
    const texts = new Set([
        ...Object.values(LetterPinyinSounds),
        ...Object.values(PinyinSpeechMap),
        ...PinyinData.combinations.map(item => item.example),
        '一声',
        '二声',
        '三声',
        '四声',
        '游戏开始！',
        '还剩一分钟！',
        '请选择一个头像',
        '请输入你的名字'
    ]);

    for (const gradeWords of Object.values(WordsData.grades)) {
        for (const word of gradeWords) {
            texts.add(word.hanzi);
        }
    }

    return [...texts].filter(Boolean).sort((a, b) => a.localeCompare(b, 'zh-CN'));
}

function run(command, args, description) {
    const result = spawnSync(command, args, { encoding: 'utf8' });

    if (result.error || result.status !== 0) {
        const detail = result.stderr?.trim() || result.error?.message || '未知错误';
        throw new Error(`${description}失败：${detail}`);
    }
}

async function hasAudioData(file) {
    try {
        const fileStats = await stat(file);
        // say 失败时可能仍会留下约 4 KB 的空文件头，不能把它当作可播放资源。
        return fileStats.size > 4096;
    } catch {
        return false;
    }
}

if (process.platform !== 'darwin') {
    throw new Error('本地语音资源生成目前需要 macOS 的 say 与 afconvert。');
}

await mkdir(assetDirectory, { recursive: true });

const voiceTexts = collectVoiceTexts();
const manifestKeys = [];
const temporaryDirectory = await mkdtemp(join(tmpdir(), 'pinyin-voice-'));

try {
    for (const text of voiceTexts) {
        const key = hashText(text);
        const wavFile = resolve(assetDirectory, `${key}.wav`);
        const aiffFile = join(temporaryDirectory, `${key}.aiff`);

        manifestKeys.push(key);

        if (!(await hasAudioData(wavFile))) {
            run('say', ['-v', 'Tingting', '-r', '170', '-o', aiffFile, text], `生成“${text}”语音`);
            run('afconvert', ['-f', 'WAVE', '-d', 'LEI16', aiffFile, wavFile], `转换“${text}”语音`);
        }
    }
} finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
}

const manifestSource = [
    '/* Generated by scripts/generate-voice-assets.mjs. */',
    `export const VoiceAssets = new Set(${JSON.stringify(manifestKeys, null, 4)});`,
    ''
].join('\n');

await writeFile(manifestFile, manifestSource, 'utf8');
console.log(`中文语音资源已生成：${manifestKeys.length} 条，音色：Tingting`);
